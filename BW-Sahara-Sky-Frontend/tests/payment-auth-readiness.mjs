import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {writeFile} from 'node:fs/promises';
const base='http://127.0.0.1:8782';
const php='C:/Users/marwa/AppData/Local/Temp/bw-hotel-php/php.exe';
const fixture='C:/Users/marwa/AppData/Local/Temp/bw-hotel-local/readiness-auth-fixture.php';
const env={...process.env,PHPRC:'C:/Users/marwa/AppData/Local/Temp/bw-payment-tests-20261007.ini'};
const command=mode=>execFileSync(php,[fixture,mode],{env,cwd:'C:/Users/marwa/AppData/Local/Temp/bw-hotel-app',stdio:'pipe'});
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const context=await browser.newContext({serviceWorkers:'block'});
const page=await context.newPage(),errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
try {
 command('cleanup');
 assert.equal((await context.request.get(base+'/api/hotel/checkout/eligibility')).status(),401);checks.push('guest payment eligibility rejected');
 assert.equal((await context.request.post(base+'/api/hotel/auth/otp/request',{data:{email:'synthetic@example.invalid'}})).status(),419);checks.push('OTP writes require CSRF');
 await page.goto(base+'/login/',{waitUntil:'networkidle'});
 const email=page.locator('.otp-gate input[name=email]');await email.waitFor();
 await email.fill('readiness-otp-20261008@example.invalid');
 const sent=page.waitForResponse(r=>r.url().endsWith('/auth/otp/request')&&r.request().method()==='POST');
 await page.locator('.otp-gate button[type=submit]').click();assert.equal((await sent).status(),200);
 await page.locator('.otp-gate input[name=code]').waitFor();checks.push('real OTP request renders code entry using local mail log');
 command('prepare'); // Simulate mailbox receipt without sending a real email.
 await page.locator('.otp-gate input[name=code]').fill('123456');
 const verified=page.waitForResponse(r=>r.url().endsWith('/auth/otp/verify'));
 await page.locator('.otp-gate button[type=submit]').click();assert.equal((await verified).status(),200);
 await page.getByRole('button',{name:'Sign out',exact:true}).waitFor();checks.push('OTP verification signs in against real backend');
 const cookies=await context.cookies(base+'/api/hotel/auth/refresh');assert(cookies.some(c=>c.name==='hotel_refresh'&&c.httpOnly&&c.sameSite==='Strict'));checks.push('HttpOnly Strict refresh cookie');
 await page.evaluate(()=>sessionStorage.setItem('sahara-stay-preview',JSON.stringify({arrival:'2026-11-05',departure:'2026-11-07',adults:'1',children:'0',roomId:2})));
 await page.goto(base+'/booking/review/',{waitUntil:'networkidle'});
 const continueButton=page.locator('.booking-aside button.button');await continueButton.waitFor();
 const eligibility=page.waitForResponse(r=>r.url().endsWith('/checkout/eligibility'));
 await continueButton.click();assert.equal((await eligibility).status(),200);
 assert.equal(new URL(page.url()).pathname,'/booking/review/');assert(page.url().includes('review'));checks.push('review continuation validates identity without false paid confirmation');
 assert.equal(errors.length,0,errors.join('; '));
 await page.route('**/api/hotel/auth/logout',r=>r.fulfill({status:503,contentType:'application/json',body:'{"message":"Synthetic failure"}'}));
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('.booking-aside button.text-link')?.disabled);
 assert(await page.evaluate(()=>Boolean(window.hotelAuth?.token)));checks.push('failed logout keeps UI signed in for retry');
 await page.unroute('**/api/hotel/auth/logout');
 const logout=page.waitForResponse(r=>r.url().endsWith('/auth/logout'));
 await page.getByRole('button',{name:'Sign out',exact:true}).click();assert.equal((await logout).status(),200);
 assert.equal((await context.request.get(base+'/api/hotel/checkout/eligibility')).status(),401);checks.push('logout clears usable authentication');
 assert.equal((await context.cookies(base+'/api/hotel/auth/refresh')).some(c=>c.name==='hotel_refresh'),false);
 await writeFile('test-results/payment-auth-readiness.json',JSON.stringify({passed:true,checks,pageErrors:errors,scope:'Local clone and synthetic mailbox receipt; no live delivery or payment'},null,2));
 console.log(JSON.stringify({passed:true,checks}));
} finally {await browser.close();command('cleanup');}
